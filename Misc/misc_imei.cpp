bool IsValidSvn (AnsiString ansi_str, unsigned char &svn)
{
    RANGE_CHECK_ERROR(!AnsiString_To_UnsignedChar(ansi_str, svn, 0, 255), RANGE_ERR_IMEI_SVN);
    return true;
}

//---------------------------------------------------------------------------
bool IsValidPad (AnsiString ansi_str, unsigned char &pad)
{
    RANGE_CHECK_ERROR(!AnsiString_To_UnsignedChar(ansi_str, pad, 0, 255), RANGE_ERR_IMEI_PAD);
    return true;
}








